export const DICTIONARIES: Record<Lang, Record<Key, string>> = { es, en };

/** The language an address asks for. English lives under "/en/" or behind "?lang=en". */
export function langOf(location: { pathname: string; search: string } | undefined): Lang {
  if (!location) return "es";
  if (/\/en\//.test(location.pathname)) return "en";
  return new URLSearchParams(location.search).get("lang") === "en" ? "en" : "es";
}

let current: Lang = langOf(typeof location === "undefined" ? undefined : location);
if (typeof document !== "undefined") document.documentElement.lang = current;

export const lang = (): Lang => current;

/** For tests. The running panel takes its language from the address and keeps it. */
export function setLang(next: Lang): void {
  current = next;
}

/** The text for `key`, with each `{name}` replaced by `params.name`. */
export function t(key: Key, params?: Record<string, string | number>): string {
  const text = DICTIONARIES[current][key];
  if (!params) return text;
  return text.replace(/\{(\w+)\}/g, (whole, name: string) => (name in params ? String(params[name]) : whole));
}

/** Picks the singular or the plural key by `count`. */
export function plural(count: number, one: Key, many: Key, params?: Record<string, string | number>): string {
  return t(count === 1 ? one : many, params);
}
